"""Guarded wrapper around unmodified pinned robomimic trainer.

Default prints the launch plan without importing torch. --execute runs training
only after a matching CPU DataLoader audit. Root controls GPU ordering/budget.
"""
from __future__ import annotations
import argparse
import datetime
import json
import os
from pathlib import Path
import shutil
import sys
import time
import traceback
from generate_configs import HERE, PINS, frozen_sources, sha, write_new, differences

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--config',type=Path,required=True)
    p.add_argument('--preflight',type=Path,required=True)
    p.add_argument('--evidence-dir',type=Path,required=True)
    p.add_argument('--upstream',type=Path,default=HERE/'upstream')
    p.add_argument('--execute',action='store_true')
    p.add_argument('--resume',action='store_true')
    args=p.parse_args()
    frozen_sources(args.upstream)
    cfg=json.loads(args.config.read_text()); proof=json.loads(args.preflight.read_text())
    if proof.get('status')!='passed' or not proof.get('loader_checked') or proof.get('config_sha256')!=sha(args.config):
        raise ValueError('Require CPU real-DataLoader preflight for this exact config')
    if proof['train_episodes']!=200 or cfg['train']['hdf5_filter_key']!='train':raise ValueError('Controlled200trainonly')
    if cfg['experiment']['rollout']['enabled']:raise ValueError('Use separate frozen collector for controlled evaluation')
    if not cfg['train']['cuda']:raise ValueError('GPU training config expected; CPU preflight is separate')
    output=Path(cfg['train']['output_dir'])/cfg['experiment']['name']
    if output.exists() and not args.resume:raise FileExistsError('Never overwrite existing experiment: '+str(output))
    if args.resume:
        runs=list(output.iterdir())
        if len(runs)!=1 or not runs[0].is_dir():raise ValueError('Resume requires exactly one existing timestamped run')
        old=json.loads((runs[0]/'config.json').read_text())
        changed=differences(old,cfg)
        if any(x['key']!='train.num_epochs' for x in changed):raise ValueError('Resume permits only extending total epochs: '+str(changed))
        if cfg['train']['num_epochs']<=old['train']['num_epochs']:raise ValueError('Resume must extend total epochs')
    plan={'status':'planned','config':str(args.config),'config_sha256':sha(args.config),'preflight_sha256':sha(args.preflight),
          'pins':PINS,'resume':args.resume,'total_updates':cfg['train']['num_epochs']*cfg['experiment']['epoch_every_n_steps'],
          'output':str(output),'scope':'200-demo official-architecture control; not full published benchmark reproduction',
          'resume_boundary':'Official optimizer/epoch resume; RNG and DataLoader cursor are not fully restored, so no bitwise-continuation claim.'}
    if not args.execute:
        print(json.dumps(plan,indent=2));return
    args.evidence_dir.mkdir(parents=True,exist_ok=False)
    write_new(args.evidence_dir/'launch.json',plan)
    write_new(args.evidence_dir/'frozen_config.json',cfg)
    os.environ.setdefault('MUJOCO_GL','egl')
    # All checkpoints in this controlled experiment are generated by our own trainer.
    # Upstream torch.load predates torch2.6's weights_only default change.
    os.environ['TORCH_FORCE_NO_WEIGHTS_ONLY_LOAD']='1'
    sys.path[:0]=[str(args.upstream/'robomimic'),str(args.upstream/'dexmimicgen')]
    import torch
    import torchvision
    import numpy as np
    from robomimic.config import config_factory
    import robomimic.utils.train_utils as TrainUtils
    from robomimic.scripts.train import train as official_train
    if not torch.cuda.is_available():raise RuntimeError('CUDA unavailable; no silent CPU training fallback')
    config=config_factory(cfg['algo_name'],dic=cfg)
    config.lock()
    torch.cuda.reset_peak_memory_stats()
    original=TrainUtils.run_epoch
    original_save=TrainUtils.save_model
    original_copy=shutil.copyfile
    rows=[]
    saves=[]
    copies=[]
    def timed_epoch(*pos,**kw):
        torch.cuda.synchronize();start=time.perf_counter()
        result=original(*pos,**kw)
        torch.cuda.synchronize();elapsed=time.perf_counter()-start
        if not all(np.isfinite(float(v)) for v in result.values()):raise ValueError('Nonfinite epoch metric')
        row={'epoch':kw.get('epoch'),'validation':kw.get('validate',False),'updates':kw.get('num_steps'),
             'seconds':elapsed,'seconds_per_batch':elapsed/kw['num_steps'],
             'peak_allocated_bytes':torch.cuda.max_memory_allocated(),
             'peak_reserved_bytes':torch.cuda.max_memory_reserved(),'metrics':result}
        rows.append(row)
        with (args.evidence_dir/'actual_epochs.jsonl').open('a') as f:f.write(json.dumps(row,allow_nan=False)+'\n')
        print('DAY4_PROFILE '+json.dumps({k:v for k,v in row.items() if k!='metrics'}),flush=True)
        return result
    def timed_save(*pos,**kw):
        start=time.perf_counter()
        result=original_save(*pos,**kw)
        path=Path(kw['ckpt_path'])
        row={'path':str(path),'seconds':time.perf_counter()-start,'bytes':path.stat().st_size}
        saves.append(row)
        print('DAY4_SAVE '+json.dumps(row),flush=True)
        return result
    def timed_copy(*pos,**kw):
        start=time.perf_counter()
        result=original_copy(*pos,**kw)
        row={'source':str(pos[0] if pos else kw['src']),
             'destination':str(pos[1] if len(pos)>1 else kw['dst']),
             'seconds':time.perf_counter()-start}
        copies.append(row)
        print('DAY4_COPY '+json.dumps(row),flush=True)
        return result
    TrainUtils.run_epoch=timed_epoch
    TrainUtils.save_model=timed_save
    shutil.copyfile=timed_copy
    start=time.perf_counter(); receipt={**plan,'status':'running','started_utc':datetime.datetime.now(datetime.timezone.utc).isoformat()}
    try:
        result=official_train(config,device=torch.device('cuda'),auto_remove_exp=False,resume=args.resume)
        receipt.update(status='complete',important_stats=result)
    except BaseException:
        receipt.update(status='failed',error=traceback.format_exc());raise
    finally:
        TrainUtils.run_epoch=original
        TrainUtils.save_model=original_save
        shutil.copyfile=original_copy
        receipt.update(wall_seconds=time.perf_counter()-start,epochs=len(rows),
                       actual_training_updates=sum(x['updates'] for x in rows if not x['validation']),
                       checkpoint_saves=saves,checkpoint_copies=copies,
                       versions={'python':sys.version,'torch':torch.__version__,'torchvision':torchvision.__version__},
                       finished_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),
                       existing_checkpoints=[str(x) for x in output.rglob('*.pth')])
        write_new(args.evidence_dir/'completion.json',receipt)

if __name__=='__main__':main()
